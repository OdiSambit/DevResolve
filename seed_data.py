SEED_USERNAME = "devresolve_samples"


def seed_if_empty() -> int:
    """Insert the sample dataset once. Returns the number of experiences created."""
    if database.count_experiences() > 0:
        return 0
    user = database.get_user_by_username(SEED_USERNAME)
    if not user:
        user = database.create_user(SEED_USERNAME, "samples@devresolve.local",
                                    auth.hash_password("not-a-real-login-account"))
    helper = database.get_user_by_username("sample_helper") or database.create_user(
        "sample_helper", "helper@devresolve.local", auth.hash_password("not-a-real-login-account"))
    created = 0
    for item in SEED_EXPERIENCES:
        alts = item.pop("alts", ())
        exp = database.create_experience(user["id"], item, is_seed=True)
        item["alts"] = alts
        for text, accepted in alts:
            database.add_solution(exp["id"], helper["id"], text, is_accepted=accepted)
        created += 1
    return created
